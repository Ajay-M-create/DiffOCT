#!/usr/bin/env python3
"""Forward-model mismatch on a digital twin of one liquid Intralipid B-scan.

Reviewer comment: the inverse verification inverts data generated by the same
forward model. How robust is recovery to mismatch such as spatially varying
backscattering and errors in gain and confocal parameters?

Truth. Synthetic B-scans reuse the calibration of the real 1% liquid
Intralipid acquisition (H focus, B-scan 256): surface (start of the CF fit
band), CF-derived gain (frame median), z_f, z_R, axial pixel size, sensitivity
roll-off S(z) and noise floor N(z). The attenuation is homogeneous and equal to
the frame-median CF estimate, so the true mu is known. Signal speckle (complex,
axial/lateral PSF sigma 1.2/1.25 px) and detector noise N(z) are summed as
fields, despeckled with the real 7 x 15 px kernel, log-compressed and quantized
to the uint16 0-150 dB TIFF encoding. The PSF widths were chosen so the
residual texture matches the real B-scan (validation.json).

Scenarios. Each row varies one parameter: a spatially varying backscattering fraction alpha
(Gaussian random field in dB, correlation sigma 10 px), a gain offset, an
unmodeled lateral gain drift, a focal-plane error, or a Rayleigh-range error.
Gain offsets alter the true signal gain; confocal errors alter the assumed
correction (focal error = assumed minus true; Rayleigh factor = assumed / true).

Inversion. The nominal single-scattering model of the liquid production
pipeline (model.py, preprocessing.py, unchanged): (I - N)/(S H) correction,
full-depth support, Adam 15,000 iterations, lr 1e-3 cosine to 1e-5, MSE and TV
weights 1000, mu in [1e-6, 20], Uniform(0, 5) initialization, final iterate.
A scalar MSE-optimal gain is re-estimated every iteration, as in the agar and
clinical protocols (the liquid validation instead uses fixed CF-derived gain).

Metrics over the 100-pixel CF window: mu_hat = mean over A-lines of the
per-A-line mean; bias = 100 (mu_hat - mu_true)/mu_true; pixel MAPE against
mu_true; delta MAPE = MAPE minus the matched-model MAPE of the same realization
(percentage points), which removes the speckle-limited floor shared by every
scenario. Mean (SD) over five realizations (speckle, alpha field, gain drift and
initialization, shared across scenarios).

Usage (scripts/run_REBUTTAL_model_mismatch.sh runs `all` on one GPU):
    python experiments/REBUTTAL_model_mismatch/mismatch.py all RUN_DIR
    python experiments/REBUTTAL_model_mismatch/mismatch.py {prepare,run,summarize} RUN_DIR

Staged to figures/data/figureS7_model_mismatch/.
"""
