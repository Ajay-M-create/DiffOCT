def write_json(path, value):
    tmp = Path(path).with_name(Path(path).name + ".tmp")
    tmp.write_text(json.dumps(value, indent=2, allow_nan=False) + "\n")
    tmp.replace(path)


def read_json(path):
    return json.loads(Path(path).read_text())


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def rng_for(seed, stream):
    """Common random numbers: streams depend on the realization, never on the scenario."""
    return np.random.default_rng(np.random.SeedSequence([BASE_SEED, seed, stream]))


def confocal_curve(zfp, zr):
    # Same convention as the liquid loader: evaluated at MATLAB depth z = 1..500.
    return 1.0 / (1.0 + ((np.arange(1, 501) - zfp) / zr) ** 2)


def load_calibration(config):
    frames, cal, sources = load_frames([config["python_bscan"]], (config["acquisition"],), config["concentration"])
    f = frames[0]
    import h5py
    with h5py.File(DATA / "CF_Method_Outputs.mat", "r") as cf:
        v = f["report"]["python_volume"]
        mu_cf = cf["mu"][v, config["python_bscan"], :, 0].astype(np.float64)
        g_prime = cf["G"][v, config["python_bscan"], :, 0].astype(np.float64)
    dz = cal["dz_water_um"] / 1000.0
    gain, fallback = fixed_cf_gain(g_prime, mu_cf, f["fit"], dz)
    valid = np.isfinite(mu_cf) & (mu_cf > 0) & ~fallback
    return dict(fit=f["fit"], surface=f["fit"].argmax(axis=0), noise=f["noise"], sensitivity=f["sensitivity"],
                zfp=float(f["report"]["zFP_px"]), zr=float(cal["zR_px"]), dz=dz,
                mu_true=float(np.median(mu_cf[valid])), gain_db=float(np.median(gain[~fallback])),
                measured_db=f["db"], sources=sources)


# ---------------------------------------------------------------- truth generator
def expected_signal(cal, scen, seed, config):
    """Noise-free linear signal G(x) alpha(z,x) mu exp(-2 tau) H(z) S(z) below the surface."""
    depth_px = np.arange(500)[:, None] - cal["surface"][None, :]
    inside = depth_px >= 0
    tau = cal["mu_true"] * np.where(inside, depth_px, 0) * cal["dz"]  # exclusive cumulative sum
    alpha_db = np.zeros((500, 500))
    if scen.get("alpha_db"):
        field = gaussian_filter(rng_for(seed, 1).standard_normal((500, 500)), config["alpha_corr_sigma_px"])
        field = (field - field[inside].mean()) / field[inside].std()
        alpha_db = scen["alpha_db"] * field
    gain_db = np.full(500, cal["gain_db"] + scen.get("gain_error_db", 0.0))
    if scen.get("gain_drift_db"):
        drift = gaussian_filter1d(rng_for(seed, 2).standard_normal(500), config["gain_drift_corr_sigma_px"])
        gain_db = gain_db + scen["gain_drift_db"] * (drift - drift.mean()) / drift.std()
    signal = 10.0 ** ((gain_db[None, :] + alpha_db + 10.0 * np.log10(cal["mu_true"])) / 10.0) \
        * np.exp(-2.0 * tau) * (confocal_curve(cal["zfp"], cal["zr"]) * cal["sensitivity"])[:, None]
    return np.where(inside, signal, 0.0)


def speckle_bases(seed, config):
    """Unit complex signal and noise fields, shared by every scenario of one realization."""
    sp = config["speckle"]
    rng = rng_for(seed, 0)
    shape = (sp["slow_axis_slices"], 500, 500)
    unit = lambda: (rng.standard_normal(shape, dtype=np.float32) + 1j * rng.standard_normal(shape, dtype=np.float32)) / np.sqrt(2)
    sig = unit()
    for axis, s in ((1, sp["axial_psf_sigma_px"]), (0, sp["lateral_psf_sigma_px"]), (2, sp["lateral_psf_sigma_px"])):
        sig = gaussian_filter1d(sig.real, s, axis=axis) + 1j * gaussian_filter1d(sig.imag, s, axis=axis)
    sig = (sig / np.sqrt(np.mean(np.abs(sig) ** 2))).astype(np.complex64)
    noi = unit().astype(np.complex64)
    w = np.exp(-0.5 * ((np.arange(shape[0]) - shape[0] // 2) / sp["sigma_slow_px"]) ** 2)
    return sig, noi, (w / w.sum()).astype(np.float32)


def measure(signal, noise, bases, config):
    """Despeckled log intensity (dB), quantized like the real TIFFs; bases=None gives the expected intensity."""
    if bases is None:
        intensity = signal + noise[:, None]
    else:
        sig, noi, w = bases
        field = np.sqrt(signal).astype(np.float32)[None] * sig + np.sqrt(noise).astype(np.float32)[None, :, None] * noi
        intensity = np.tensordot(w, np.abs(field) ** 2, axes=(0, 0)).astype(np.float64)
        intensity = gaussian_filter1d(intensity, config["speckle"]["sigma_fast_px"], axis=1)
    hi = config["quantization_db_range"][1]
    raw = np.clip(np.round(10.0 * np.log10(intensity) * 65535.0 / hi), 0, 65535)
    return raw * hi / 65535.0


def correct(meas, cal, scen):
    """Correction and masks with the parameters the inversion ASSUMES."""
    confocal = confocal_curve(cal["zfp"] + scen.get("zf_error_px", 0.0), cal["zr"] * scen.get("zr_factor", 1.0))
    return correct_and_mask(meas, cal["noise"], cal["sensitivity"], confocal, cal["fit"])


def residual_sd(target, mask):
    """Texture SD: residual about a per-A-line line fit, minus the mean residual depth profile."""
    res = np.full((int(mask.sum(axis=0).max()), target.shape[1]), np.nan)
    for x in range(target.shape[1]):
        z = np.flatnonzero(mask[:, x])
        if len(z) >= 10:
            res[:len(z), x] = target[z, x] - np.polyval(np.polyfit(z, target[z, x], 1), z)
    return float(np.nanstd(res - np.nanmean(res, axis=1, keepdims=True)))


# ---------------------------------------------------------------- prepare
def prepare(run, config):
    import torch
    run.mkdir(parents=True, exist_ok=True)
    write_json(run / "config.json", config)
    write_json(run / "scenarios.json", SCENARIOS)
    cal = load_calibration(config)
    write_json(run / "calibration.json", dict(concentration_percent=config["concentration"], acquisition=config["acquisition"],
               matlab_bscan=config["python_bscan"] + 1, mu_true=cal["mu_true"], gain_db=cal["gain_db"],
               zfp_px=cal["zfp"], zr_px=cal["zr"], dz_mm=cal["dz"], sources=cal["sources"]))
    # Check 1: noiseless matched data are reproduced by the nominal model at the true mu.
    signal = expected_signal(cal, SCENARIOS[0], 0, config)
    prep = correct(measure(signal, cal["noise"], None, config), cal, SCENARIOS[0])
    tm = prep["full_depth_transport_mask"]
    pred = forward_db(torch.as_tensor(np.where(tm, cal["mu_true"], 1.0)[None]), torch.as_tensor(tm[None]), cal["dz"])[0].numpy() + cal["gain_db"]
    strong = prep["full_depth_loss_mask"] & (signal > 10 * cal["noise"][:, None])
    err = float(np.abs(pred - prep["target_db"])[strong].max())
    # Check 2: synthetic speckle texture vs the real B-scan.
    real = correct_and_mask(cal["measured_db"], cal["noise"], cal["sensitivity"], confocal_curve(cal["zfp"], cal["zr"]), cal["fit"])
    arrays = {k: [] for k in ["target_db", "loss_mask", "transport_mask", "comparison_mask", "init_mu"]}
    for seed in config["seeds"]:
        bases = speckle_bases(seed, config)
        init = np.maximum(rng_for(seed, 3).uniform(0, 5, (500, 500)), config["mu_bounds"][0]).astype(np.float32)
        for scen in SCENARIOS:
            prep = correct(measure(expected_signal(cal, scen, seed, config), cal["noise"], bases, config), cal, scen)
            arrays["target_db"].append(prep["target_db"].astype(np.float32))
            arrays["loss_mask"].append(prep["full_depth_loss_mask"])
            arrays["transport_mask"].append(prep["full_depth_transport_mask"])
            arrays["comparison_mask"].append(prep["comparison_mask"])
            arrays["init_mu"].append(init)
            if seed == config["seeds"][0] and scen["key"] == "matched":
                texture = dict(synthetic_db=residual_sd(prep["target_db"], prep["comparison_mask"]),
                               real_db=residual_sd(real["target_db"], real["comparison_mask"]))
        print(f"prepared realization {seed}", flush=True)
    validation = dict(noiseless_matched_max_abs_err_db=err, noiseless_pixels=int(strong.sum()),
                      noiseless_status="PASS" if err < 0.05 else "CHECK", texture_residual_sd=texture,
                      texture_status="PASS" if 0.7 < texture["synthetic_db"] / texture["real_db"] < 1.3 else "CHECK")
    write_json(run / "validation.json", validation)
    print(json.dumps(validation, indent=2), flush=True)
    if "CHECK" in (validation["noiseless_status"], validation["texture_status"]):
        raise RuntimeError("Simulator validation failed")
    out = {k: np.stack(v) for k, v in arrays.items()}  # frame order: realization-major, then scenario
    np.savez_compressed(run / "synthetic.npz", mu_true=np.float64(cal["mu_true"]), dz=np.float64(cal["dz"]), **out)


# ---------------------------------------------------------------- inversion
def run_inversion(run, config):
    import torch
    device = "cuda" if torch.cuda.is_available() else "cpu"
    with np.load(run / "synthetic.npz") as f:
        d = {k: f[k] for k in f.files}
    rows = np.flatnonzero(d["transport_mask"].any(axis=(0, 2)))
    start, stop = int(rows[0]), int(rows[-1] + 1)
    t = lambda a, dt=torch.float32: torch.as_tensor(np.ascontiguousarray(a[:, start:stop]), dtype=dt, device=device)
    target, loss_mask, trans = t(d["target_db"]), t(d["loss_mask"], torch.bool), t(d["transport_mask"], torch.bool)
    B, _, X = target.shape
    dz = float(d["dz"])
    counts = loss_mask.sum(dim=(1, 2)).clamp_min(1)
    mu = torch.nn.Parameter(t(d["init_mu"]))
    opt = torch.optim.Adam([mu], lr=config["learning_rate"], betas=tuple(config["adam_betas"]), eps=config["adam_eps"])
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, T_max=config["iterations"],
                                                       eta_min=config["learning_rate"] * config["final_lr_factor"])
    print(f"Inverting {B} B-scans on {device}", flush=True)
    t0 = time.time()
    for it in range(config["iterations"] + 1):
        # MSE-optimal scalar gain per B-scan (manuscript Eq. gain_reopt). Detached: dL/dG = 0 at the optimum,
        # so the gradient with respect to mu is the same as differentiating through G*.
        with torch.no_grad():
            g = ((target - forward_db(mu, trans, dz)) * loss_mask).sum(dim=(1, 2)) / counts
        gain = g[:, None].expand(B, X).contiguous()
        opt.zero_grad(set_to_none=True)
        total, mse, _, tv = objective(mu, target, loss_mask, trans, dz, gain, config["mse_weight"], config["tv_weight"])
        if it % 5000 == 0:
            print(f"  iter {it:6d}  mean objective {total.mean().item():.3f}  mean MSE {mse.mean().item():.4f}", flush=True)
        if it == config["iterations"]:
            break
        total.sum().backward()
        opt.step()
        sched.step()
        with torch.no_grad():
            mu.clamp_(*config["mu_bounds"])
    mu_final = np.full(d["target_db"].shape, np.nan, dtype=np.float32)
    mu_final[:, start:stop] = mu.detach().cpu().numpy()
    np.savez_compressed(run / "results.npz", mu_final=mu_final, gain_db=g.cpu().numpy(), mse_db2=mse.detach().cpu().numpy())
    write_json(run / "run_complete.json", dict(seconds=time.time() - t0, device=device, frames=B,
               gpu=torch.cuda.get_device_name(0) if device == "cuda" else None,
               slurm_job_id=os.environ.get("SLURM_JOB_ID"), utc=datetime.now(timezone.utc).isoformat()))


# ---------------------------------------------------------------- summarize
def summarize(run, config):
    with np.load(run / "synthetic.npz") as f:
        cmask, mu_true = f["comparison_mask"], float(f["mu_true"])
    with np.load(run / "results.npz") as f:
        mu, mse = f["mu_final"], f["mse_db2"]
    S, R = len(SCENARIOS), len(config["seeds"])
    per_run = []
    for i in range(S * R):
        seed, si = config["seeds"][i // S], i % S
        m = cmask[i]
        counts = m.sum(axis=0)
        ok = counts >= config["min_cf_pixels_per_aline"]
        per_aline = np.where(m, mu[i], 0.0).sum(axis=0)[ok] / counts[ok]
        mu_hat = float(per_aline.mean())
        per_run.append(dict(scenario=KEYS[si], seed=seed, mu_true=mu_true, mu_hat=mu_hat,
                            bias_percent=100 * (mu_hat - mu_true) / mu_true,
                            mape_percent=float(100 * np.mean(np.abs(mu[i][m] - mu_true)) / mu_true),
                            mse_db2=float(mse[i])))
    matched = {r["seed"]: r["mape_percent"] for r in per_run if r["scenario"] == "matched"}
    for r in per_run:
        r["delta_mape_pp"] = r["mape_percent"] - matched[r["seed"]]
    with open(run / "metrics_per_run.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(per_run[0]))
        w.writeheader()
        w.writerows(per_run)
    summary = []
    for scen in SCENARIOS:
        rs = [r for r in per_run if r["scenario"] == scen["key"]]
        row = dict(scenario=scen["key"], label=scen["label"])
        for k in ["mu_hat", "bias_percent", "mape_percent", "delta_mape_pp", "mse_db2"]:
            v = np.array([r[k] for r in rs])
            row[f"{k}_mean"], row[f"{k}_sd"] = float(v.mean()), float(v.std(ddof=1))
        summary.append(row)
    with open(run / "summary_table.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(summary[0]))
        w.writeheader()
        w.writerows(summary)
    (run / "table_model_mismatch.tex").write_text(latex_table(summary, mu_true, config))
    print((run / "table_model_mismatch.tex").read_text())
    STAGE.mkdir(parents=True, exist_ok=True)
    files = ["summary_table.csv", "metrics_per_run.csv", "table_model_mismatch.tex",
             "config.json", "scenarios.json", "calibration.json", "validation.json"]
    for name in files:
        shutil.copy2(run / name, STAGE / name)
    write_json(STAGE / "source_manifest.json", dict(run=str(run), staged_utc=datetime.now(timezone.utc).isoformat(),
               script="experiments/REBUTTAL_model_mismatch/mismatch.py", sha256={n: sha256(STAGE / n) for n in files}))
    print(f"Staged to {STAGE}")


def latex_table(summary, mu_true, config):
    signed = lambda v: f"{v:+.1f}".replace("-", "$-$")
    lines = [
        "\\begin{tabular}{lcccc}",
        "\\toprule",
        "Mismatch in simulated data & $\\hat\\mu$ (mm$^{-1}$) & Bias (\\%) & MAPE (\\%) & $\\Delta$MAPE (pp) \\\\",
        "\\midrule",
    ]
    for r in summary:
        delta = ("--" if r["scenario"] == "matched"
                 else f"{signed(r['delta_mape_pp_mean'])} ({r['delta_mape_pp_sd']:.1f})")
        lines.append(f"{r['label']} & {r['mu_hat_mean']:.3f} ({r['mu_hat_sd']:.3f}) & "
                     f"{signed(r['bias_percent_mean'])} ({r['bias_percent_sd']:.1f}) & "
                     f"{r['mape_percent_mean']:.1f} ({r['mape_percent_sd']:.1f}) & {delta} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(lines)


